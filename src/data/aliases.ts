/**
 * 探すときの別の呼び名。
 *
 * 表に出す言い方は大谷派のものに揃えてあるので（釈尊、御文、法名）、
 * ふだん口にしている言い方で打つと見つからない。「釈迦」で探して
 * 〇件、ということが起きる。
 *
 * ここに書いたものは検索のためだけに使う。画面には出さない。
 */
export type Alias = {
  /** 素材の本文に出てくる語 */
  term: string
  /** 同じものを指して打たれそうな言い方 */
  also: string[]
  /**
   * これを含むときは付けない。
   * 「六波羅蜜寺」は寺の名で、六波羅蜜の教えの話ではない。
   * 語の一致だけで拾うと、こういう取り違えが起きる。
   */
  except?: string[]
}

